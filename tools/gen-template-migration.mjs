// Writes db/platform/migrations/20261103000500_workflow_templates.sql from the bundled ComfyUI
// workflows in tools/comfyui/templates, so the platform defaults in the database are those files
// (ADR-0035: the files stay the shipped source; the database holds the copy a world resolves).
// A test (apps/adaptation/test/template-seed.test.ts) fails when the migration and the files differ.
//   node tools/gen-template-migration.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
export const KINDS = {
  workflow_sprite: "sprite",
  workflow_cg: "cg",
  workflow_bg: "background",
  workflow_clothes: "clothes",
  workflow_adornment: "adornment",
  workflow_object: "object",
};
export const OUT = resolve(root, "db/platform/migrations/20261103000500_workflow_templates.sql");

/**
 * The graph as the database keeps it: the prompt text is blanked. db/ carries no prompt text, and the
 * server writes both prompts into every run (injectWorkflowParams), so nothing is lost.
 */
export function forDatabase(graph) {
  const copy = JSON.parse(JSON.stringify(graph));
  for (const node of Object.values(copy)) {
    if (node.class_type === "CLIPTextEncode") node.inputs.text = "";
  }
  return copy;
}

export function bundled(file) {
  return JSON.parse(readFileSync(resolve(root, `tools/comfyui/templates/${file}.template.api.json`), "utf8"));
}

export function build() {
  const bodies = Object.entries(KINDS).map(([kind, file]) => {
    const json = JSON.stringify(forDatabase(bundled(file)));
    return `    ('${kind}', $tpl$${json}$tpl$::jsonb)`;
  });
  return `-- GENERATED by tools/gen-template-migration.mjs from tools/comfyui/templates. Do not edit by hand.
-- 015 workflow templates (F-71): the six asset workflows become the platform defaults. Clothes,
-- adornment and object get their own kinds; the nodes the bundled graphs use join the allow-list;
-- each kind gets the bundled graph as its next version and the platform pin moves to it. A visual
-- novel keeps the version it was pinned to (pin_all_templates), so nothing already made changes.

insert into platform.template_kinds (key, label, body_kind, max_bytes, sort_order) values
  ('workflow_clothes',   'Clothes workflow',    'comfy_graph', 262144, 12),
  ('workflow_adornment', 'Adornment workflow',  'comfy_graph', 262144, 14),
  ('workflow_object',    'Object workflow',     'comfy_graph', 262144, 16);

update platform.allowed_node_types
   set kind_keys = kind_keys || array['workflow_clothes', 'workflow_adornment', 'workflow_object']
 where 'workflow_sprite' = any (kind_keys);

insert into platform.allowed_node_types (class_type, kind_keys) values
  ('RMBG', array['workflow_sprite', 'workflow_cg', 'workflow_bg', 'workflow_clothes', 'workflow_adornment', 'workflow_object']),
  ('TorchCompileDiffusionOpenVINO', array['workflow_sprite', 'workflow_cg', 'workflow_bg', 'workflow_clothes', 'workflow_adornment', 'workflow_object']);

do $seed$
declare
  r      record;
  v_t    uuid;
  v_v    uuid;
  v_no   int;
  v_sum  text;
  v_same boolean;
begin
  -- the owner publishes the shipped defaults directly; people go through publish_template
  alter table platform.templates disable trigger templates_transition;

  for r in select * from (values
${bodies.join(",\n")}
  ) as t (kind, body) loop
    perform platform.assert_template_valid(r.kind, r.body, '{}'::jsonb);       -- a bad seed stops the migration
    v_sum := encode(sha256(convert_to(r.body::text || '|' || '{}'::jsonb::text, 'UTF8')), 'hex');

    select id into v_t from platform.templates where kind_key = r.kind and scope_type = 'platform';
    if v_t is null then
      insert into platform.templates (kind_key, scope_type) values (r.kind, 'platform') returning id into v_t;
    end if;

    select exists (select 1 from platform.template_versions where template_id = v_t and checksum = v_sum) into v_same;
    if v_same then
      continue;
    end if;

    select coalesce(max(version_no), 0) + 1 into v_no from platform.template_versions where template_id = v_t;
    insert into platform.template_versions (template_id, kind_key, version_no, body, param_map, checksum, note)
      values (v_t, r.kind, v_no, r.body, '{}'::jsonb, v_sum, 'bundled ComfyUI workflow')
      returning id into v_v;
    update platform.templates set publish_status_key = 'published', head_version_id = v_v where id = v_t;
    insert into platform.template_pins (scope_type, kind_key, template_version_id)
      values ('platform', r.kind, v_v)
      on conflict (scope_type, scope_key, kind_key)
      do update set template_version_id = excluded.template_version_id, pinned_at = now();
  end loop;

  alter table platform.templates enable trigger templates_transition;
end $seed$;
`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  writeFileSync(OUT, build());
  console.log(`wrote ${OUT}`);
}
